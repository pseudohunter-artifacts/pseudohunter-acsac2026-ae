"""Re-pretrain BERT on expanded corpus (1400+ benign APKs).

Uses data/pretrain_cache_v2/ (generated by build_spmlm_corpus.py from
1340 AndroZoo + 68 Happer benign APKs, ~8M sequences).

This produces a much better BERT initialization than the original 68-APK
pretraining, with diverse app coverage improving generalization.

Usage:
    python scripts/experiments/run_spmlm_pretrain_v2.py [--epochs 10] [--device cuda]

Output:
    outputs/experiments/pseudo_bert_v3/pretrained_bert_v2.pt
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

import torch

from android_packer.decoders.pseudo_tokenizer import (
    BYTE_REPRESENTATIONS,
    BYTE_REPRESENTATION_LEGACY_RAW,
)
from android_packer.models.fusion_encoder import FusionEncoderConfig, build_fusion_encoder
from android_packer.training.pretrain_spmlm import SpMLMConfig, train_spmlm

PRETRAIN_CACHE = ROOT / "data" / "pretrain_cache_v2"
OUT_DIR = ROOT / "outputs" / "experiments" / "pseudo_bert_v3"


def load_corpus(cache_dir: Path, max_length: int = 128, max_sequences: int = 0):
    """Load cached corpus from npz files. FAST: uses numpy slicing, no .tolist()."""
    meta_path = cache_dir / "corpus_meta.json"
    if not meta_path.exists():
        raise FileNotFoundError(f"No corpus_meta.json in {cache_dir}")

    with open(meta_path) as f:
        meta = json.load(f)

    print(f"  Corpus: {meta['n_sequences']} sequences from {meta['n_apks']} APKs")
    print(f"  Streams: Dalvik={meta['streams']['dalvik']}, "
          f"Native={meta['streams']['native']}, Byte={meta['streams']['byte']}")

    # Calculate how many chunks we need
    target = max_sequences if max_sequences > 0 else meta["n_sequences"]
    n_chunks_needed = min(meta["n_chunks"], (target + meta["chunk_size"] - 1) // meta["chunk_size"])

    # Load chunks as numpy arrays (FAST)
    all_ids, all_types, all_masks, all_abnormal = [], [], [], []
    loaded = 0

    for chunk_idx in range(n_chunks_needed):
        chunk_path = cache_dir / f"corpus_chunk_{chunk_idx:04d}.npz"
        if not chunk_path.exists():
            continue
        data = np.load(chunk_path)
        n = len(data["token_ids"])

        # Truncate to max_length (already stored at correct length, but be safe)
        ids = data["token_ids"][:, :max_length]
        types = data["token_type_ids"][:, :max_length]
        masks = data["attention_mask"][:, :max_length]
        abnormal = data["abnormal_mask"][:, :max_length]

        # Pad if sequence length < max_length
        if ids.shape[1] < max_length:
            pad_w = max_length - ids.shape[1]
            ids = np.pad(ids, ((0, 0), (0, pad_w)))
            types = np.pad(types, ((0, 0), (0, pad_w)))
            masks = np.pad(masks, ((0, 0), (0, pad_w)))
            abnormal = np.pad(abnormal, ((0, 0), (0, pad_w)))

        remaining = target - loaded
        if n > remaining:
            ids = ids[:remaining]
            types = types[:remaining]
            masks = masks[:remaining]
            abnormal = abnormal[:remaining]

        all_ids.append(ids)
        all_types.append(types)
        all_masks.append(masks)
        all_abnormal.append(abnormal)
        loaded += len(ids)

        if (chunk_idx + 1) % 5 == 0:
            print(f"    Loaded chunk {chunk_idx+1}/{n_chunks_needed}: "
                  f"{loaded} sequences", flush=True)

        if loaded >= target:
            break

    # Concatenate all chunks
    all_ids = np.concatenate(all_ids).astype(np.int16)
    all_types = np.concatenate(all_types).astype(np.int8)
    all_masks = np.concatenate(all_masks).astype(np.int8)
    all_abnormal = np.concatenate(all_abnormal).astype(np.int8)

    print(f"  Loaded {loaded} sequences [{all_ids.shape}]", flush=True)

    # Convert to list-of-dicts format expected by train_spmlm
    corpus = []
    for i in range(loaded):
        corpus.append({
            "token_ids": all_ids[i].tolist(),
            "token_type_ids": all_types[i].tolist(),
            "attention_mask": all_masks[i].tolist(),
            "abnormal_mask": all_abnormal[i].tolist(),
        })

    return corpus, meta


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--epochs", type=int, default=10,
                        help="Pretraining epochs")
    parser.add_argument("--batch-size", type=int, default=64,
                        help="Batch size (larger for pretraining)")
    parser.add_argument("--lr", type=float, default=1e-4)
    parser.add_argument("--max-length", type=int, default=128)
    parser.add_argument("--max-sequences", type=int, default=200000,
                        help="Max corpus size (0=all, default 200K for memory)")
    parser.add_argument("--cache-dir", type=Path, default=PRETRAIN_CACHE,
                        help="Prebuilt spMLM corpus directory")
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR,
                        help="Output directory for checkpoints and final weights")
    parser.add_argument("--byte-representation", type=str, default=None,
                        choices=BYTE_REPRESENTATIONS,
                        help="Expected byte-path representation; defaults to corpus metadata or legacy_raw")
    parser.add_argument("--bert-layers", type=int, default=4)
    parser.add_argument("--bert-dim", type=int, default=256)
    parser.add_argument("--device", type=str, default="auto")
    parser.add_argument("--normality-loss-weight", type=float, default=0.0,
                        help="B4 auxiliary clean-vs-corrupted normality loss weight")
    parser.add_argument("--corruption-prob", type=float, default=0.35,
                        help="Fraction of clean sequences paired with corrupted sequences")
    parser.add_argument("--resume-from", type=str, default=None,
                        help="Resume from checkpoint (e.g., epoch_020.pt path)")
    parser.add_argument("--start-epoch", type=int, default=0,
                        help="Starting epoch (used with --resume-from)")
    args = parser.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    device = torch.device(
        "cuda" if args.device == "auto" and torch.cuda.is_available()
        else args.device if args.device != "auto" else "cpu"
    )
    print(f"Device: {device}")
    print(f"Config: {args.epochs} epochs, batch={args.batch_size}, "
          f"lr={args.lr}, max_len={args.max_length}")

    # Load corpus
    print(f"\nLoading corpus from {args.cache_dir}...")
    t0 = time.time()
    corpus, corpus_meta = load_corpus(args.cache_dir, args.max_length, args.max_sequences)
    print(f"  Loaded {len(corpus)} sequences [{time.time()-t0:.1f}s]")

    if not corpus:
        print("ERROR: No corpus loaded!")
        return

    # Shuffle for diversity
    rng = np.random.RandomState(42)
    rng.shuffle(corpus)

    byte_representation = (
        args.byte_representation
        or corpus_meta.get("byte_representation")
        or BYTE_REPRESENTATION_LEGACY_RAW
    )
    if corpus_meta.get("byte_representation") and args.byte_representation:
        if corpus_meta["byte_representation"] != args.byte_representation:
            raise ValueError(
                "corpus byte_representation does not match argument: "
                f"{corpus_meta['byte_representation']} vs {args.byte_representation}"
            )
    vocab_size = int(corpus_meta.get("vocab_size", 0) or 0)

    # Build model (FusionEncoder contains the BERT)
    print("\nBuilding model...")
    fusion_cfg = FusionEncoderConfig(
        bert_hidden_dim=args.bert_dim, bert_n_layers=args.bert_layers,
        bert_max_length=args.max_length, bert_n_heads=8,
        bert_intermediate_dim=args.bert_dim * 2,
        byte_representation=byte_representation,
    )
    encoder = build_fusion_encoder(fusion_cfg)
    if vocab_size and vocab_size != encoder.bert.cfg.vocab_size:
        raise ValueError(
            f"corpus vocab_size={vocab_size} but model vocab_size={encoder.bert.cfg.vocab_size}"
        )
    n_bert = sum(p.numel() for n, p in encoder.named_parameters() if "bert" in n)
    print(f"  BERT params: {n_bert:,}")

    # Resume from checkpoint if specified
    if args.resume_from:
        resume_path = Path(args.resume_from)
        if not resume_path.exists():
            # Try relative to checkpoints dir
            resume_path = args.out_dir / "checkpoints" / args.resume_from
        if resume_path.exists():
            print(f"\n  Resuming from: {resume_path}")
            state_dict = torch.load(resume_path, map_location="cpu")
            encoder.load_state_dict(state_dict)
            print(f"  Loaded checkpoint OK")
        else:
            print(f"  ERROR: Cannot find checkpoint {args.resume_from}")
            return

    # spMLM pretraining with periodic checkpoints (every 5 epochs)
    save_every = 5
    total_epochs = args.epochs
    print(f"\n=== spMLM Pretraining ({len(corpus)} sequences, {total_epochs} epochs, "
          f"save every {save_every}) ===")

    ckpt_dir = args.out_dir / "checkpoints"
    ckpt_dir.mkdir(parents=True, exist_ok=True)

    epochs_done = args.start_epoch
    while epochs_done < total_epochs:
        chunk_epochs = min(save_every, total_epochs - epochs_done)
        spmlm_cfg = SpMLMConfig(
            epochs=chunk_epochs,
            batch_size=args.batch_size,
            learning_rate=args.lr,
            vocab_size=encoder.bert.cfg.vocab_size,
            device=str(device),
            use_fp16=(device.type == "cuda"),
            normality_loss_weight=args.normality_loss_weight,
            corruption_prob=args.corruption_prob,
        )
        encoder = train_spmlm(encoder, corpus, spmlm_cfg)
        epochs_done += chunk_epochs

        # Save checkpoint
        ckpt_path = ckpt_dir / f"epoch_{epochs_done:03d}.pt"
        torch.save(encoder.state_dict(), ckpt_path)
        print(f"  [Checkpoint] Saved: {ckpt_path.name} (epoch {epochs_done}/{total_epochs})",
              flush=True)

    # Save final as the default path (for downstream scripts)
    out_path = args.out_dir / "pretrained_bert_v2.pt"
    torch.save(encoder.state_dict(), out_path)
    print(f"\n  Final saved: {out_path} ({out_path.stat().st_size / 1e6:.1f} MB)")

    full_state_path = args.out_dir / "pretrained_fusion_v2.pt"
    torch.save({"fusion_encoder": encoder.state_dict()}, full_state_path)
    print(f"  Saved: {full_state_path}")


if __name__ == "__main__":
    main()
